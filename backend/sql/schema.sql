-- Apache Derby / Java DB. Ejecutar UNA VEZ sobre la base AcademicaDB.
-- JPA no crea ni elimina tablas al desplegar: persistence.xml usa action=none.
CREATE TABLE ESTUDIANTE (
    CODIGO VARCHAR(20) NOT NULL PRIMARY KEY,
    NOMBRE VARCHAR(100) NOT NULL,
    CORREO VARCHAR(150) NOT NULL
);
CREATE TABLE CURSO (
    CODIGO VARCHAR(20) NOT NULL PRIMARY KEY,
    NOMBRE VARCHAR(100) NOT NULL,
    CREDITOS INTEGER NOT NULL CHECK (CREDITOS BETWEEN 1 AND 30),
    SEMESTRE INTEGER NOT NULL CHECK (SEMESTRE BETWEEN 1 AND 20),
    ESTUDIANTES_ADMITIDOS INTEGER NOT NULL CHECK (ESTUDIANTES_ADMITIDOS BETWEEN 1 AND 1000)
);
CREATE TABLE ESTUDIANTE_CURSO (
    ESTUDIANTE_CODIGO VARCHAR(20) NOT NULL,
    CURSO_CODIGO VARCHAR(20) NOT NULL,
    CONSTRAINT PK_ESTUDIANTE_CURSO PRIMARY KEY (ESTUDIANTE_CODIGO, CURSO_CODIGO),
    CONSTRAINT FK_INSCRIPCION_ESTUDIANTE FOREIGN KEY (ESTUDIANTE_CODIGO) REFERENCES ESTUDIANTE(CODIGO),
    CONSTRAINT FK_INSCRIPCION_CURSO FOREIGN KEY (CURSO_CODIGO) REFERENCES CURSO(CODIGO)
);
-- Derby crea los índices necesarios para las llaves foráneas.
